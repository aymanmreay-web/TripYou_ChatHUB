#!/usr/bin/env python3
"""Generate db/seed/0001_catalog.sql from packages/contracts/*.json"""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
c = root / "packages" / "contracts"
perms = json.loads((c / "permissions.json").read_text(encoding="utf-8"))["permissions"]
mods = json.loads((c / "modules.json").read_text(encoding="utf-8"))["modules"]
roles = json.loads((c / "roles.json").read_text(encoding="utf-8"))["roles"]
q = lambda s: "NULL" if s is None else "'" + str(s).replace("'", "''") + "'"
out = ["-- GENERATED by tools/gen_seed.py — do not edit by hand", "begin;"]
for p in perms:
    out.append(f"insert into hub.permissions(key,grp,label_ar,super_only) values ({q(p['key'])},{q(p['group'])},{q(p['label_ar'])},{str(p['super_only']).lower()}) on conflict (key) do update set grp=excluded.grp,label_ar=excluded.label_ar,super_only=excluded.super_only;")
for r in roles:
    out.append(f"insert into hub.roles(key,title_ar,is_system) values ({q(r['key'])},{q(r['title_ar'])},true) on conflict (key) do update set title_ar=excluded.title_ar;")
    if r.get("all"):
        keys = [p["key"] for p in perms]
    elif r.get("all_except_super_only"):
        keys = [p["key"] for p in perms if not p["super_only"]]
    else:
        keys = r.get("perms", [])
    for k in keys:
        out.append(f"insert into hub.role_permissions(role_id,permission_key) select id,{q(k)} from hub.roles where key={q(r['key'])} on conflict do nothing;")
for m in mods:
    out.append(f"insert into hub.feature_modules(key,area,title_ar,status,required_permission,sort) values ({q(m['key'])},{q(m['area'])},{q(m['title_ar'])},{q(m['status'])},{q(m['required_permission'])},{m['sort']}) on conflict (key) do update set area=excluded.area,title_ar=excluded.title_ar,required_permission=excluded.required_permission,sort=excluded.sort;")
out.append("commit;")
(root / "db" / "seed").mkdir(parents=True, exist_ok=True)
(root / "db" / "seed" / "0001_catalog.sql").write_text("\n".join(out) + "\n", encoding="utf-8")
print("ok", len(perms), "permissions", len(roles), "roles", len(mods), "modules")
